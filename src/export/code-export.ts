import type { VectorDocument } from '../core/document';
import type { ExportVariable } from '../core/types';
import { exportDocumentToSvg } from './svg-export';

export interface CodeExportOptions {
  componentName?: string;
  variableIds?: Iterable<string>;
}

export function exportReactComponent(document: VectorDocument, options: CodeExportOptions = {}): string {
  const componentName = sanitizeComponentName(options.componentName ?? 'VectorAsset');
  const variables = selectedVariables(document, options.variableIds);
  const names = variableNames(variables);
  const binding = (name: ExportVariable['binding']) => variables.find((variable) => variable.binding === name);
  const stroke = binding('strokeWidth');
  const color = binding('fillColor');
  const scale = binding('scale');
  const opacity = binding('opacity');
  const svg = exportDocumentToSvg(document, {
    precision: 3,
    exportBoundsMode: 'artwork',
    includeMetadata: false,
    ...(color ? { strokeColor: '__VS_STROKE_COLOR__', fillColor: '__VS_FILL_COLOR__' } : {}),
    // Unit widths retain each instance's transform/alignment multiplier. Only
    // explicitly exposed widths are substituted; other artwork stays baked.
    ...(stroke ? { strokeWidth: 1 } : {}),
  }).replaceAll(/\sdata-(?:segment|region)-id="[^"]*"/g, '');
  const propLines = variables.map((variable) =>
    `  ${names.get(variable.id)}?: ${variable.type === 'color' ? 'string' : 'number'};`,
  );
  const defaults = variables.map((variable, index) =>
    `  ${names.get(variable.id)}: value${index} = ${JSON.stringify(defaultValue(variable))},`,
  );
  const valueExpression = (variable: ExportVariable | undefined, fallback: string) => {
    if (!variable) return fallback;
    const value = `value${variables.indexOf(variable)}`;
    if (variable.type === 'color') return `escapeAttribute(${value})`;
    const [min, max] = numericBounds(variable);
    return `clampNumber(${value}, ${min}, ${max}, ${defaultValue(variable)})`;
  };
  const substitutions: string[] = [];
  if (color) {
    // Callback replacements treat dollar-sign sequences as literal input, not
    // String.replace replacement directives. All attribute data is XML-escaped.
    substitutions.push(`    .replaceAll('__VS_STROKE_COLOR__', () => ${valueExpression(color, "'currentColor'")})`);
    substitutions.push(`    .replaceAll('__VS_FILL_COLOR__', () => ${valueExpression(color, "'currentColor'")})`);
  }
  if (stroke) {
    substitutions.push(`    .replaceAll(/stroke-width="([\\d.eE+-]+)"/g, (_match, width: string) => \`stroke-width="\${Number(width) * ${valueExpression(stroke, '1.25')}}"\`)`);
  }
  substitutions.push(`    .replace('<svg ', () => \`<svg role="img" aria-label="\${escapeAttribute(title ?? '${componentName}')}" \`)`);

  return `import type { CSSProperties } from 'react';

export interface ${componentName}Props {
${propLines.join('\n')}${propLines.length ? '\n' : ''}  className?: string;
  style?: CSSProperties;
  title?: string;
}

const SVG_MARKUP = ${JSON.stringify(svg)};

function escapeAttribute(value: unknown): string {
  return String(value).replace(/[&<>"']/g, (character) => {
    switch (character) {
      case '&': return '&amp;';
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '"': return '&quot;';
      default: return '&#39;';
    }
  });
}
${variables.some((variable) => variable.type === 'number') ? `
function clampNumber(value: number, min: number, max: number, fallback: number): number {
  return Number.isFinite(value) ? Math.min(max, Math.max(min, value)) : fallback;
}
` : ''}
/** Generated by Keyline. Geometry is solved and contains no runtime constraint engine. */
export function ${componentName}({
${defaults.join('\n')}${defaults.length ? '\n' : ''}  className,
  style,
  title,
}: ${componentName}Props) {
  const markup = SVG_MARKUP
${substitutions.join('\n')};
  return (
    <span
      className={className}
      style={{
        display: 'inline-block',
        lineHeight: 0,
        transform: \`scale(\${${valueExpression(scale, '1')}})\`,
        transformOrigin: 'center',
        opacity: ${valueExpression(opacity, '1')},
        ...style,
      }}
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
`;
}

export function exportCssVariables(document: VectorDocument, variableIds?: Iterable<string>): string {
  const variables = selectedVariables(document, variableIds);
  const used = new Set<string>();
  const names = new Map<string, string>();
  for (const variable of variables) {
    const base = cssName(variable.name);
    let name = base;
    for (let suffix = 2; used.has(name); suffix += 1) name = `${base}-${suffix}`;
    used.add(name);
    names.set(variable.id, name);
  }
  const declarations = variables.map((variable) =>
    `  --${names.get(variable.id)}: ${defaultValue(variable)}${variable.type === 'number' && variable.binding === 'strokeWidth' ? 'px' : ''};`,
  );
  const colorName = names.get(variables.find((item) => item.binding === 'fillColor')?.id ?? '') ?? 'asset-color';
  const opacityName = names.get(variables.find((item) => item.binding === 'opacity')?.id ?? '') ?? 'asset-opacity';
  return `:root {\n${declarations.join('\n')}\n}\n\n.vector-studio-asset {\n  color: var(--${colorName}, currentColor);\n  opacity: var(--${opacityName}, 1);\n}\n`;
}

function selectedVariables(document: VectorDocument, ids?: Iterable<string>): ExportVariable[] {
  const selected = ids ? new Set(ids) : null;
  return [...document.exportVariables.values()]
    .filter((variable) => !selected || selected.has(variable.id))
    .sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
}

function sanitizeComponentName(value: string): string {
  const words = value.replace(/[^a-zA-Z0-9]+/g, ' ').trim().split(/\s+/).filter(Boolean);
  const result = words.map((word) => word[0].toUpperCase() + word.slice(1)).join('') || 'VectorAsset';
  return /^\d/.test(result) ? `Asset${result}` : result;
}

function sanitizePropName(value: string): string {
  const words = value.replace(/[^a-zA-Z0-9]+/g, ' ').trim().split(/\s+/).filter(Boolean);
  const [first = 'value', ...rest] = words;
  const result = first[0].toLowerCase() + first.slice(1) + rest.map((word) => word[0].toUpperCase() + word.slice(1)).join('');
  return /^\d/.test(result) ? `value${result}` : result;
}

function variableNames(variables: ExportVariable[]): Map<string, string> {
  // Public prop names cannot collide with built-in props. Local aliases also
  // prevent reserved words and helper names from becoming JS bindings.
  const used = new Set(['className', 'style', 'title']);
  const names = new Map<string, string>();
  for (const variable of variables) {
    const base = sanitizePropName(variable.name);
    let name = base;
    for (let suffix = 2; used.has(name); suffix += 1) name = `${base}${suffix}`;
    used.add(name);
    names.set(variable.id, name);
  }
  return names;
}

function numericBounds(variable: ExportVariable): [number, number] {
  const floor = 0;
  const ceiling = variable.binding === 'opacity' ? 1 : variable.binding === 'scale' ? 100 : 1024;
  const min = typeof variable.min === 'number' && Number.isFinite(variable.min) ? Math.max(floor, Math.min(ceiling, variable.min)) : floor;
  const max = typeof variable.max === 'number' && Number.isFinite(variable.max) ? Math.max(min, Math.min(ceiling, variable.max)) : ceiling;
  return [min, max];
}

function defaultValue(variable: ExportVariable): number | string {
  if (variable.type === 'color') {
    const color = String(variable.value).trim();
    // CSS exports are source code, not HTML attributes: reject declaration
    // delimiters and external URL paints instead of relying on XML escaping.
    return /^(?:#[\da-fA-F]{3,8}|[a-zA-Z]+|(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\([-+\w.,%/\s]*\)|var\(--[\w-]+\))$/.test(color) ? color : 'currentColor';
  }
  const [min, max] = numericBounds(variable);
  return typeof variable.value === 'number' && Number.isFinite(variable.value) ? Math.min(max, Math.max(min, variable.value)) : min;
}

function cssName(value: string): string {
  return value.trim().replace(/([a-z])([A-Z])/g, '$1-$2').replace(/[^a-zA-Z0-9-]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase() || 'value';
}
