import type { VectorDocument } from '../core/document';
import type { ExportVariable } from '../core/types';
import { exportDocumentToSvg } from './svg-export';

export interface CodeExportOptions {
  componentName?: string;
  variableIds?: Iterable<string>;
}

export function exportReactComponent(document: VectorDocument, options: CodeExportOptions = {}): string {
  const componentName = sanitizeComponentName(options.componentName ?? 'VectorAsset');
  const variables = selectedVariables(document, options.variableIds);
  const svg = exportDocumentToSvg(document, {
    precision: 3,
    exportBoundsMode: 'artwork',
    includeMetadata: false,
    strokeColor: '__VS_STROKE_COLOR__',
    fillColor: '__VS_FILL_COLOR__',
  }).replaceAll(/\sdata-(?:segment|region)-id="[^"]*"/g, '');
  const markup = JSON.stringify(svg);
  const propLines = variables.map((variable) =>
    `  ${sanitizePropName(variable.name)}?: ${variable.type === 'color' ? 'string' : 'number'};`,
  );
  const defaults = variables.map((variable) =>
    `  ${sanitizePropName(variable.name)} = ${literal(variable.value)},`,
  );
  const binding = (name: ExportVariable['binding']) => variables.find((variable) => variable.binding === name);
  const stroke = binding('strokeWidth');
  const color = binding('fillColor');
  const scale = binding('scale');
  const opacity = binding('opacity');
  const strokeExpression = stroke ? sanitizePropName(stroke.name) : '1.25';
  const colorExpression = color ? sanitizePropName(color.name) : `'currentColor'`;
  const scaleExpression = scale ? sanitizePropName(scale.name) : '1';
  const opacityExpression = opacity ? sanitizePropName(opacity.name) : '1';

  return `import type { CSSProperties } from 'react';

export interface ${componentName}Props {
${propLines.join('\n')}${propLines.length ? '\n' : ''}  className?: string;
  style?: CSSProperties;
  title?: string;
}

const SVG_MARKUP = ${markup};

/** Generated by Keyline. Geometry is solved and contains no runtime constraint engine. */
export function ${componentName}({
${defaults.join('\n')}${defaults.length ? '\n' : ''}  className,
  style,
  title,
}: ${componentName}Props) {
  const markup = SVG_MARKUP
    .replaceAll('__VS_STROKE_COLOR__', String(${colorExpression}))
    .replaceAll('__VS_FILL_COLOR__', String(${colorExpression}))
    .replaceAll('stroke-width="1.25"', \`stroke-width="\${${strokeExpression}}"\`)
    .replace('<svg ', \`<svg role="img" aria-label="\${title ?? '${componentName}'}" \`);
  return (
    <span
      className={className}
      style={{
        display: 'inline-block',
        lineHeight: 0,
        transform: \`scale(\${${scaleExpression}})\`,
        transformOrigin: 'center',
        opacity: ${opacityExpression},
        ...style,
      }}
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
`;
}

export function exportCssVariables(document: VectorDocument, variableIds?: Iterable<string>): string {
  const variables = selectedVariables(document, variableIds);
  const declarations = variables.map((variable) =>
    `  --${cssName(variable.name)}: ${variable.value}${variable.type === 'number' && variable.binding === 'strokeWidth' ? 'px' : ''};`,
  );
  return `:root {\n${declarations.join('\n')}\n}\n\n.vector-studio-asset {\n  color: var(--${cssName(variables.find((item) => item.binding === 'fillColor')?.name ?? 'asset-color')}, currentColor);\n  opacity: var(--${cssName(variables.find((item) => item.binding === 'opacity')?.name ?? 'asset-opacity')}, 1);\n}\n`;
}

function selectedVariables(document: VectorDocument, ids?: Iterable<string>): ExportVariable[] {
  const selected = ids ? new Set(ids) : null;
  return [...document.exportVariables.values()]
    .filter((variable) => !selected || selected.has(variable.id))
    .sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
}

function sanitizeComponentName(value: string): string {
  const words = value.replace(/[^a-zA-Z0-9]+/g, ' ').trim().split(/\s+/).filter(Boolean);
  const result = words.map((word) => word[0].toUpperCase() + word.slice(1)).join('') || 'VectorAsset';
  return /^\d/.test(result) ? `Asset${result}` : result;
}

function sanitizePropName(value: string): string {
  const words = value.replace(/[^a-zA-Z0-9]+/g, ' ').trim().split(/\s+/).filter(Boolean);
  const [first = 'value', ...rest] = words;
  const result = first[0].toLowerCase() + first.slice(1) + rest.map((word) => word[0].toUpperCase() + word.slice(1)).join('');
  return /^\d/.test(result) ? `value${result}` : result;
}

function cssName(value: string): string {
  return value.trim().replace(/([a-z])([A-Z])/g, '$1-$2').replace(/[^a-zA-Z0-9-]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase() || 'value';
}

function literal(value: number | string): string {
  return typeof value === 'number' ? String(value) : JSON.stringify(value);
}
